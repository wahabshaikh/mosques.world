export function clientMessages(locale: Locale): Record<string, string> | null {
  return locale === DEFAULT_LOCALE ? null : CATALOGS[locale as Exclude<Locale, "en">];
}

/** The same lookup on the server, for server components that share these strings. */
export function clientText(locale: Locale) {
  const messages = clientMessages(locale);
  return (source: string, vars?: Record<string, string | number>) => {
    const template = messages?.[source] ?? source;
    return vars ? template.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match)) : template;
  };
}
